function collect() {
  const meta = spawnSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: path.join(ROOT, "app", "src-tauri"), encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
  if (meta.status !== 0) throw new Error(`cargo metadata failed: ${meta.stderr}`);
  const comps = read("library/components.json");
  const fonts = read("library/fonts.json");
  const ff = fs.readFileSync(path.join(ROOT, "scripts", "fetch-ffmpeg.mjs"), "utf8");
  const sidecars = fs.readFileSync(path.join(ROOT, "scripts", "fetch-sidecars.mjs"), "utf8");
  return {
    engine: npmRows(read("engine/package-lock.json")),
    runner: npmRows(read("runner/package-lock.json")),
    ui: npmRows(read("app/package-lock.json")),
    crates: crateRows(JSON.parse(meta.stdout)),
    library: { commit: comps.commit, components: comps.components.length, licenses: comps.licenses, fonts: (fonts.fonts ?? fonts.families ?? Object.keys(fonts).filter((k) => !k.startsWith("$"))).length },
    ffmpeg: { version: /version: "([^"]+BtbN[^"]+)"/.exec(ff)?.[1] ?? "see ffmpeg/LICENSE.txt", tag: /ffmpeg-(n[\d.]+-\d+-g[0-9a-f]+)/.exec(ff)?.[1] ?? "the pinned tag" },
    icons: read("library/icons.json").families,
    node: /NODE_VERSION\s*=\s*"([^"]+)"/.exec(sidecars)?.[1] ?? /v(\d+\.\d+\.\d+)/.exec(sidecars)?.[1] ?? "",
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(collect());
  if (process.argv.includes("--check")) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (now !== text) {
      console.error("THIRD-PARTY-NOTICES.md is out of date: run node scripts/notices.mjs");
      process.exit(1);
    }
    console.log("THIRD-PARTY-NOTICES.md is up to date");
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
