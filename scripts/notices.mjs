#!/usr/bin/env node
// notices.mjs: writes THIRD-PARTY-NOTICES.md, the list of everything the
// installer ships that someone else made, with its license (PRD 11, phase 4).
// The app bundles it next to the program (tauri.conf.json resources) and the
// About page points to it.
//
// Sources, all pinned in this repo:
//   - the npm lockfiles of the engine, the runner and the UI (production only)
//   - the Rust crates the app is built from (cargo metadata, normal deps)
//   - the sidecars and the library: Node, ffmpeg (GPL, with where its source
//     is), the HyperFrames registry components and presets, the fonts, the
//     open-design styles
//
// Usage: node scripts/notices.mjs [--check]
//   --check: exit 1 if the committed file is not what this would write (tests)

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "THIRD-PARTY-NOTICES.md");
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));

// npm: the packages a lockfile installs for production, one row per name and version.
export function npmRows(lock) {
  const rows = new Map();
  for (const [key, p] of Object.entries(lock.packages ?? {})) {
    if (!key || p.dev || p.link) continue;
    const name = key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
    rows.set(`${name}@${p.version}`, { name, version: p.version, license: p.license ?? "see the package" });
  }
  return [...rows.values()];
}

// Rust: the crates reachable from the app through normal dependencies.
export function crateRows(meta) {
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const stack = [meta.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? []) {
      if ((d.dep_kinds ?? []).some((k) => k.kind === null || k.kind === "build")) stack.push(d.pkg);
    }
  }
  seen.delete(meta.resolve.root);
  return [...seen].map((id) => byId.get(id)).filter(Boolean).map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? "see the crate's license file" : "see the crate") }));
}

const byName = (a, b) => a.name.localeCompare(b.name) || String(a.version).localeCompare(String(b.version));
const table = (rows) => ["| Package | Version | License |", "|---|---|---|", ...rows.sort(byName).map((r) => `| ${r.name} | ${r.version} | ${r.license} |`)].join("\n");

